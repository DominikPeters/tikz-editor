import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { renderTikzToSvgAsync } from "../../../packages/core/src/render/index";
import { OPEN_EXAMPLE_CATALOG } from "../../../packages/app/src/ui/examples/open-example-catalog";
import { renderOpenExamplePreviewWithRenderer, type OpenExamplePreview } from "../../../packages/app/src/ui/examples/render-open-example-preview";

async function main(): Promise<void> {
  const generated: Record<string, OpenExamplePreview> = {};
  for (const example of OPEN_EXAMPLE_CATALOG) {
    generated[example.id] = await renderOpenExamplePreviewWithRenderer(example, renderTikzToSvgAsync);
  }

  const moduleSource = [
    "// This file is auto-generated by web/scripts/generate-open-example-previews.ts.",
    "// Do not edit it manually.",
    "",
    "export type GeneratedOpenExamplePreview = {",
    "  exampleId: string;",
    "  svg: string | null;",
    "  warningCount: number;",
    "  errorCount: number;",
    "  errorMessage: string | null;",
    "};",
    "",
    `export const GENERATED_OPEN_EXAMPLE_PREVIEWS: Record<string, GeneratedOpenExamplePreview> = ${JSON.stringify(generated, null, 2)};`,
    ""
  ].join("\n");

  const thisDir = dirname(fileURLToPath(import.meta.url));
  const outputPath = resolve(thisDir, "../../../packages/app/src/ui/examples/generated-open-example-previews.ts");
  const previous = await readIfExists(outputPath);
  if (previous === moduleSource) {
    console.log("[open-example-previews] up to date");
    return;
  }

  await writeFile(outputPath, moduleSource, "utf8");
  console.log("[open-example-previews] wrote", outputPath);
}

async function readIfExists(path: string): Promise<string | null> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

void main().catch((error) => {
  console.error("[open-example-previews] generation failed:", error);
  process.exitCode = 1;
});
