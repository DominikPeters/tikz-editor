// Extracts the documented pgfplots key names (and nothing else) from the
// manual sources in pgfplots-docs/ into
// packages/core/src/pgfplots/documented-keys.generated.ts.
// Key names are the documented interface (design/pgfplots.md section 2);
// no implementation file is read. Run: node scripts/extract-pgfplots-key-names.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const docs = "pgfplots-docs";
const files = readdirSync(docs).filter((f) => f.endsWith(".tex"));
const names = new Set();
const envRe = /\\begin\{((?:pgfplots)?(?:xyz?)?(?:append)?(?:expression)?(?:code|codetwo|style|codeargs)?key(?:list)?|(?:xy)?stylekey|keylist|tikzkey(?:list)?)\}\s*\{/g;
const shortRe = /\\pgfplotsshort(xy)?stylekeys?\s+([^=]+)=/g;

function readBraced(text, start) {
  let depth = 1; let i = start;
  for (; i < text.length && depth > 0; i += 1) {
    if (text[i] === "\\") { i += 1; continue; }
    if (text[i] === "{") depth += 1; else if (text[i] === "}") depth -= 1;
  }
  return text.slice(start, i - 1);
}
function splitTop(text) {
  const out = []; let depth = 0; let cur = "";
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (c === "\\") { cur += c + (text[i + 1] ?? ""); i += 1; continue; }
    if (c === "{") depth += 1; if (c === "}") depth -= 1;
    if (c === "," && depth === 0) { out.push(cur); cur = ""; continue; }
    cur += c;
  }
  out.push(cur);
  return out;
}
function clean(spec, xy) {
  let s = spec.replace(/%[^\n]*/g, "").replace(/\s+/g, " ").trim();
  s = s.split(/=|\(initially|\(default|\\marg|\\meta|\\mchoice|\\oarg/)[0].trim();
  s = s.replace(/^\/pgfplots\//, "").replace(/^\/tikz\//, "tikz:");
  if (s.startsWith("tikz:") || s.startsWith("/")) return [];
  if (!s || /[\\$]/.test(s.replace(/\\x\\ |\\x /g, "").replace(/\\x/g, ""))) {
    if (!/\\x/.test(s)) return [];
  }
  const variants = xy || /\\x/.test(s) ? ["x", "y", "z"].map((v) => s.replace(/\\x\\ /g, `${v} `).replace(/\\x /g, v).replace(/\\x/g, v)) : [s];
  return variants.map((v) => v.replace(/\s+/g, " ").trim()).filter((v) => v && !/[\\${}]/.test(v));
}
for (const file of files) {
  const text = readFileSync(join(docs, file), "utf8");
  for (const m of text.matchAll(envRe)) {
    const env = m[1];
    const arg = readBraced(text, m.index + m[0].length);
    const xy = env.includes("xy");
    const parts = env.includes("list") ? splitTop(arg) : [arg];
    for (const part of parts) for (const n of clean(part, xy)) names.add(n);
  }
  for (const m of text.matchAll(shortRe)) {
    for (const part of m[2].split(",")) for (const n of clean(part, !!m[1])) names.add(n);
  }
}
const sorted = [...names].filter((n) => n.length > 1 && !n.includes("/.") ).sort();
const body = `// Generated by scripts/extract-pgfplots-key-names.mjs from the pgfplots manual
// (documented key names only). Do not edit by hand.
export const DOCUMENTED_PGFPLOTS_KEYS: ReadonlySet<string> = new Set(${JSON.stringify(sorted, null, 0).replace(/","/g, "\",\n  \"").replace(/^\["/, "[\n  \"").replace(/"\]$/, "\"\n]")});
`;
writeFileSync("packages/core/src/pgfplots/documented-keys.generated.ts", body);
console.log(sorted.length, "keys");
