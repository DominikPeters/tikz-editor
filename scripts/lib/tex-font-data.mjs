import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

export const TEX_FONT_DATA_PATH = resolve(
  process.cwd(),
  "packages/core/src/text/tex/fonts/data/computer-modern-ot1.generated.ts"
);

// The table is compact JSON in one single-quoted string literal (only `\`
// and `'` escaped): bundlers and engines read a string in one step, where
// the same table as an object literal costs Rollup gigabytes of syntax tree
// in every bundle.
const OPEN = "export const COMPUTER_MODERN_OT1_FONTS = JSON.parse(";
const CLOSE = ") as GeneratedTexFontTable;";

export function readTexFontData(path = TEX_FONT_DATA_PATH) {
  const source = readFileSync(path, "utf8");
  const from = source.indexOf(OPEN);
  const to = source.lastIndexOf(CLOSE);
  if (from < 0 || to < from) {
    throw new Error(`Could not extract generated font table from ${path}`);
  }
  return JSON.parse(source.slice(from + OPEN.length + 1, to - 1).replace(/\\([\\'])/gu, "$1"));
}

export function writeTexFontData(fonts, path = TEX_FONT_DATA_PATH) {
  writeFileSync(path, `// Generated by scripts/generate-tex-font-data.mjs. Do not edit by hand.
import type { GeneratedTexFontTable } from "../types.js";

// Compact JSON in a string: far cheaper to parse and bundle than an object literal.
${OPEN}'${JSON.stringify(fonts).replace(/[\\']/gu, "\\$&")}'${CLOSE}
`);
}
