import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const TEX_FONT_DATA_PATH = resolve(
  process.cwd(),
  "packages/core/src/text/tex/fonts/data/computer-modern-ot1.generated.ts"
);

// Glyph outlines are most of the data but only painting needs them, so each
// font's outlines are a module of their own, loaded when a render first asks.
export const TEX_FONT_OUTLINES_DIR = resolve(
  process.cwd(),
  "packages/core/src/text/tex/fonts/data/outlines"
);

const HEADER = "// Generated by scripts/generate-tex-font-data.mjs. Do not edit by hand.\n";

// Each table is compact JSON in one single-quoted string literal (only `\`
// and `'` escaped): bundlers and engines read a string in one step, where
// the same table as an object literal costs Rollup gigabytes of syntax tree
// in every bundle.
const OPEN = "export const COMPUTER_MODERN_OT1_FONTS = JSON.parse(";
const CLOSE = ") as GeneratedTexFontTable;";
const OUTLINES_OPEN = "export default JSON.parse(";
const OUTLINES_CLOSE = ") as TexGlyphOutlines;";
const OUTLINES_INDEX = "index.generated.ts";

function quoted(value) {
  return `'${JSON.stringify(value).replace(/[\\']/gu, "\\$&")}'`;
}

function unquoted(source, open, close, path) {
  const from = source.indexOf(open);
  const to = source.lastIndexOf(close);
  if (from < 0 || to < from) {
    throw new Error(`Could not extract generated font data from ${path}`);
  }
  return JSON.parse(source.slice(from + open.length + 1, to - 1).replace(/\\([\\'])/gu, "$1"));
}

function outlinesFileName(id) {
  return `${id}.generated.ts`;
}

/** The whole table, each font with its `glyphs` outlines. */
export function readTexFontData(path = TEX_FONT_DATA_PATH, outlinesDir = TEX_FONT_OUTLINES_DIR) {
  const fonts = unquoted(readFileSync(path, "utf8"), OPEN, CLOSE, path);
  for (const [id, font] of Object.entries(fonts)) {
    const outlinesPath = join(outlinesDir, outlinesFileName(id));
    if (font.glyphs || !existsSync(outlinesPath)) continue;
    font.glyphs = unquoted(readFileSync(outlinesPath, "utf8"), OUTLINES_OPEN, OUTLINES_CLOSE, outlinesPath);
  }
  return fonts;
}

export function writeTexFontData(fonts, path = TEX_FONT_DATA_PATH, outlinesDir = TEX_FONT_OUTLINES_DIR) {
  const metrics = {};
  const outlines = {};
  for (const [id, { glyphs, ...font }] of Object.entries(fonts)) {
    metrics[id] = font;
    outlines[id] = glyphs ?? {};
  }
  writeFileSync(path, `${HEADER}import type { GeneratedTexFontTable } from "../types.js";

// Compact JSON in a string: far cheaper to parse and bundle than an object literal.
${OPEN}${quoted(metrics)}${CLOSE}
`);
  mkdirSync(outlinesDir, { recursive: true });
  const files = new Set([OUTLINES_INDEX]);
  for (const [id, glyphs] of Object.entries(outlines)) {
    files.add(outlinesFileName(id));
    writeFileSync(join(outlinesDir, outlinesFileName(id)), `${HEADER}import type { TexGlyphOutlines } from "../../types.js";

${OUTLINES_OPEN}${quoted(glyphs)}${OUTLINES_CLOSE}
`);
  }
  // Literal import paths, so every bundler and Node split and resolve them alike.
  writeFileSync(join(outlinesDir, OUTLINES_INDEX), `${HEADER}import type { TexGlyphOutlines } from "../../types.js";

export const TEX_GLYPH_OUTLINE_LOADERS: Readonly<Record<string, () => Promise<{ readonly default: TexGlyphOutlines }>>> = {
${Object.keys(outlines).map((id) => `  ${JSON.stringify(id)}: () => import("./${id}.generated.js"),`).join("\n")}
};
`);
  for (const file of readdirSync(outlinesDir)) {
    if (!files.has(file)) rmSync(join(outlinesDir, file));
  }
}
